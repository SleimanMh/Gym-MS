export type Lang = "en" | "ar";

export function t(lang: Lang, key: Key | string, vars?: Record<string, string | number>): string {
  const dict = lang === "ar" ? ar : en;
  let s = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? dict.generic;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const locale = (lang: Lang) => (lang === "ar" ? "ar-LB" : "en-GB");
